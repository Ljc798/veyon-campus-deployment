CREATE POLICY admin_profiles_read_self ON public.admin_profiles
    FOR SELECT TO authenticated
    USING (user_id = (SELECT auth.uid()));

CREATE POLICY campuses_read_site_admins ON public.campuses
    FOR SELECT TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.admin_profiles AS profile
            WHERE profile.user_id = (SELECT auth.uid())
              AND profile.role IN ('owner', 'admin', 'editor', 'viewer')
        )
    );

